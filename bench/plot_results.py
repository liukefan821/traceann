#!/usr/bin/env python3
"""Render TraceANN paper figures + LaTeX table from a bench CSV.

Usage:
    python3 bench/plot_results.py [csv] [out_dir]

Defaults:
    csv     = bench/results/paper.csv
    out_dir = bench/figures

Outputs:
    fig1_vo_vs_d.{pdf,png}   VO size & opened leaves vs ambient dimension d
    fig2_vo_vs_ef.{pdf,png}  opened / VO size / recall vs search beam ef
    fig3_vo_vs_n.{pdf,png}   opened / VO size vs index size n (log x)
    fig4_sift1m.{pdf,png}    VO-recall Pareto + latencies on SIFT1M
    table1_d_sweep.tex       booktabs table for the d sweep
    table2_sift.tex          booktabs table for the SIFT1M eval

Requires: pandas, matplotlib  (pip install pandas matplotlib)
"""

import os
import sys

import pandas as pd
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

BLUE = "#1f4e79"
ORANGE = "#c55a11"
GREEN = "#2e7d32"
GRAY = "#7f7f7f"

plt.rcParams.update(
    {
        "font.family": "serif",
        "font.size": 9,
        "axes.grid": True,
        "grid.alpha": 0.25,
        "grid.linewidth": 0.4,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "savefig.bbox": "tight",
        "figure.dpi": 200,
    }
)


def save(fig, out_dir, name):
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(out_dir, f"{name}.{ext}"))
    plt.close(fig)
    print(f"  wrote {name}.pdf / .png")


def med_p95(ax, x, med, p95, color, ylabel, xlabel):
    ax.plot(x, med, "o-", color=color, lw=1.4, ms=3.5, label="median")
    ax.plot(x, p95, "--", color=color, lw=0.9, alpha=0.55, label="p95")
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, fontsize=8)


def fig_d(df, out):
    dd = df[df.sweep == "d"].sort_values("d")
    if dd.empty:
        print("  [skip] fig1: no 'd' sweep rows")
        return
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.8, 2.3))
    med_p95(
        a1, dd.d, dd.proof_bytes_med / 1024, dd.proof_bytes_p95 / 1024,
        BLUE, "VO size (KiB)", "ambient dimension $d$",
    )
    med_p95(
        a2, dd.d, dd.opened_med, dd.opened_p95,
        ORANGE, "opened leaves", "ambient dimension $d$",
    )
    save(fig, out, "fig1_vo_vs_d")


def fig_ef(df, out):
    ee = df[df.sweep == "ef"].sort_values("ef")
    if ee.empty:
        print("  [skip] fig2: no 'ef' sweep rows")
        return
    fig, (a1, a2, a3) = plt.subplots(1, 3, figsize=(6.8, 2.1))
    med_p95(a1, ee.ef, ee.opened_med, ee.opened_p95,
            ORANGE, "opened leaves", "search beam $ef$")
    med_p95(a2, ee.ef, ee.proof_bytes_med / 1024, ee.proof_bytes_p95 / 1024,
            BLUE, "VO size (KiB)", "search beam $ef$")
    a3.plot(ee.ef, ee.recall_at_k, "s-", color=GREEN, lw=1.4, ms=3.5)
    a3.set_xlabel("search beam $ef$")
    a3.set_ylabel("recall@$k$")
    a3.set_ylim(0, 1.02)
    save(fig, out, "fig2_vo_vs_ef")


def fig_n(df, out):
    base = df[df.sweep == "n"]
    extra = df[(df.sweep == "ef") & (df.ef == 64)]
    nn = (
        pd.concat([base, extra])
        .drop_duplicates(subset=["n"])
        .sort_values("n")
    )
    if len(nn) < 2:
        print("  [skip] fig3: not enough 'n' sweep rows")
        return
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.8, 2.3))
    for ax in (a1, a2):
        ax.set_xscale("log")
    med_p95(a1, nn.n, nn.opened_med, nn.opened_p95,
            ORANGE, "opened leaves", "index size $n$ (log)")
    med_p95(a2, nn.n, nn.proof_bytes_med / 1024, nn.proof_bytes_p95 / 1024,
            BLUE, "VO size (KiB)", "index size $n$ (log)")
    save(fig, out, "fig3_vo_vs_n")


def table_d(df, out):
    dd = df[df.sweep == "d"].sort_values("d")
    if dd.empty:
        print("  [skip] table1: no 'd' sweep rows")
        return
    rows = []
    for _, r in dd.iterrows():
        b_per_leaf = r.proof_bytes_med / max(r.opened_med, 1)
        rows.append(
            f"{int(r.d)} & {r.recall_at_k:.3f} & {r.opened_med:.0f} & "
            f"{r.proof_bytes_med / 1024:.0f} & {b_per_leaf:.0f} & "
            f"{r.prove_us_med:.0f} & {r.verify_us_med:.0f} & "
            f"{r.prove_over_search:.1f}$\\times$ \\\\"
        )
    tex = (
        "% Auto-generated by bench/plot_results.py -- do not edit by hand.\n"
        "\\begin{tabular}{rrrrrrrr}\n\\toprule\n"
        "$d$ & recall@$k$ & opened & VO (KiB) & B/leaf & "
        "prove ($\\mu$s) & verify ($\\mu$s) & overhead \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    with open(os.path.join(out, "table1_d_sweep.tex"), "w") as f:
        f.write(tex)
    print("  wrote table1_d_sweep.tex")



def fig_sift(df, out):
    ss = df[df.sweep == "sift"].sort_values("ef")
    if ss.empty:
        print("  [skip] fig4: no 'sift' rows")
        return
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(6.8, 2.3))
    a1.plot(ss.recall_at_k, ss.proof_bytes_med / 1024, "o-",
            color=BLUE, lw=1.4, ms=3.5)
    for _, r in ss.iterrows():
        a1.annotate(f"ef={int(r.ef)}",
                    (r.recall_at_k, r.proof_bytes_med / 1024),
                    textcoords="offset points", xytext=(4, 4), fontsize=7)
    a1.set_xlabel("recall@$k$ (official GT)")
    a1.set_ylabel("VO size (KiB)")
    a1.set_ylim(bottom=0)
    a2.semilogy(ss.ef, ss.search_us_med, "o-", color=GRAY,
                lw=1.4, ms=3.5, label="search")
    a2.semilogy(ss.ef, ss.prove_us_med, "s-", color=BLUE,
                lw=1.4, ms=3.5, label="prove")
    a2.semilogy(ss.ef, ss.verify_us_med, "^-", color=ORANGE,
                lw=1.4, ms=3.5, label="verify")
    a2.set_xlabel("search beam $ef$")
    a2.set_ylabel("latency ($\\mu$s, log)")
    a2.legend(frameon=False, fontsize=8)
    save(fig, out, "fig4_sift1m")


def table_sift(df, out):
    ss = df[df.sweep == "sift"].sort_values("ef")
    if ss.empty:
        print("  [skip] table2: no 'sift' rows")
        return
    rows = []
    for _, r in ss.iterrows():
        rows.append(
            f"{int(r.ef)} & {r.recall_at_k:.3f} & {r.opened_med:.0f} & "
            f"{r.proof_bytes_med / 1024:.0f} & {r.search_us_med:.0f} & "
            f"{r.prove_us_med:.0f} ({r.prove_over_search:.1f}$\\times$) & "
            f"{r.verify_us_med / 1000:.1f} \\\\"
        )
    tex = (
        "% Auto-generated by bench/plot_results.py -- do not edit by hand.\n"
        "\\begin{tabular}{rrrrrrr}\n\\toprule\n"
        "$ef$ & recall@$k$ & opened & VO (KiB) & search ($\\mu$s) & "
        "prove ($\\mu$s) & verify (ms) \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    with open(os.path.join(out, "table2_sift.tex"), "w") as f:
        f.write(tex)
    print("  wrote table2_sift.tex")


def main():
    out = sys.argv[2] if len(sys.argv) > 2 else "bench/figures"
    os.makedirs(out, exist_ok=True)
    if len(sys.argv) > 1:
        paths = [sys.argv[1]]
    else:
        paths = [p for p in ("bench/results/paper.csv", "bench/results/sift1m.csv")
                 if os.path.exists(p)]
    frames = []
    for p in paths:
        f = pd.read_csv(p)
        if "data" not in f.columns:
            f["data"] = "uniform"
        print(f"loaded {len(f)} rows from {p}")
        frames.append(f)
    df = pd.concat(frames, ignore_index=True)
    # Drop the pathological uniform baseline when structured data exists.
    if (df.data == "clustered").any():
        df = df[df.data != "uniform"]
    fig_d(df, out)
    fig_ef(df, out)
    fig_n(df, out)
    table_d(df, out)
    fig_sift(df, out)
    table_sift(df, out)
    print(f"done -> {out}/")


if __name__ == "__main__":
    main()
